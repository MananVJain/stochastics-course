#!/usr/bin/env bash
# Rewrites the one-line Dockerfile on the `binder` branch to point at a pinned image.
# Creates the branch the first time. Usage: update_binder_branch.sh <image-reference>
set -euo pipefail

IMAGE_REF="${1:?usage: update_binder_branch.sh <image-reference>}"
REMOTE_URL="${REMOTE_URL:-https://x-access-token:${GITHUB_TOKEN}@github.com/${GITHUB_REPOSITORY}.git}"

work="$(mktemp -d)"
cd "$work"
git init -q
git config user.name "github-actions"
git config user.email "actions@users.noreply.github.com"
git remote add origin "$REMOTE_URL"

if git ls-remote --exit-code --heads origin binder >/dev/null 2>&1; then
  git fetch -q --depth=1 origin binder
  git checkout -q -b binder FETCH_HEAD
else
  git checkout -q --orphan binder
fi

printf '# Auto-generated by GitHub Actions. Do not edit.\nFROM %s\n' "$IMAGE_REF" > Dockerfile
git add Dockerfile

if [ -z "$(git status --porcelain)" ]; then
  echo "binder branch already up to date"
else
  git commit -q -m "Use image ${IMAGE_REF}"
  git push -q origin binder
  echo "binder branch updated to ${IMAGE_REF}"
fi
